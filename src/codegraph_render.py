"""
Renders the code graph as `docs/CODEMAP.md`: the version of it an agent reads instead of exploring.

The markdown carries no line numbers and no file sizes, so it only changes when the structure does
(a function added, an import, a table, a route, an event). Line numbers are one `show` away.

Read it by section, not whole: every section has a stable heading, so `grep -n "^## "` or a search
for `### src/sync.py` lands on the part you need.
"""

from __future__ import annotations

from collections import Counter, defaultdict

from src.codegraph import Graph

DOC_WIDTH = 150
LIST_CAP = 10
DEF_CAP = 40


def _short(module_id: str) -> str:
    return module_id[4:] if module_id.startswith("src.") else module_id


def _names(items, cap: int = LIST_CAP) -> str:
    items = sorted(set(items))
    if not items:
        return "—"
    more = f" +{len(items) - cap}" if len(items) > cap else ""
    return ", ".join(items[:cap]) + more


def _trim(text: str, width: int = DOC_WIDTH) -> str:
    text = " ".join(text.split())
    return text if len(text) <= width else text[: width - 1].rstrip() + "…"


def _sccs(graph: dict[str, set[str]]) -> list[list[str]]:
    """Strongly connected components with more than one member (Tarjan, iterative enough for ~200 nodes)."""
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    stack: list[str] = []
    on: set[str] = set()
    out: list[list[str]] = []
    counter = [0]

    def visit(v: str) -> None:
        index[v] = low[v] = counter[0]
        counter[0] += 1
        stack.append(v)
        on.add(v)
        for w in sorted(graph.get(v, ())):
            if w not in index:
                visit(w)
                low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp = []
            while True:
                w = stack.pop()
                on.discard(w)
                comp.append(w)
                if w == v:
                    break
            if len(comp) > 1:
                out.append(sorted(comp))

    for v in sorted(graph):
        if v not in index:
            visit(v)
    return sorted(out)


def render(data: dict) -> str:
    g = Graph(data)
    nodes = g.nodes
    modules = [n for n in data["nodes"] if n["kind"] == "module"]
    src = [m for m in modules if m["layer"] == "src"]
    scripts = [m for m in modules if m["layer"] == "scripts"]
    tests = [m for m in modules if m["layer"] == "tests"]

    def edges_from(node_id: str, kind: str):
        return [e for e in g.out.get(node_id, []) if e["kind"] == kind]

    def edges_to(node_id: str, kind: str):
        return [e for e in g.into.get(node_id, []) if e["kind"] == kind]

    def owner_module(node_id: str) -> str:
        return node_id.split(":", 1)[0]

    meta = data["meta"]
    c = meta["counts"]
    out: list[str] = []
    w = out.append

    w("# Code map")
    w("")
    w("> Generated by `python scripts/code_graph.py` from the source. **Do not edit by hand**; a test fails when it")
    w("> no longer matches the code. The same graph as data is `docs/codegraph/graph.json` (every node and edge).")
    w("")
    w(f"{c['module']} modules ({len(src)} src, {len(scripts)} scripts, {len(tests)} tests) · "
      f"{c['function'] + c['method']} functions and methods · {c['class']} classes · {c['table']} tables · "
      f"{c['route']} routes · {c['event']} log events · schema version {meta['schema_version']}.")
    w("")
    w("## How to use this instead of exploring")
    w("")
    w("- Find where something lives: search this file for the name. Every module has a `### path` heading.")
    w("- Ask the graph a question without reading code: `python scripts/code_graph.py show <name>` prints a node and")
    w("  everything pointing at it or leaving it. `<name>` can be a module (`src.sync`), a function (`incremental_sync`),")
    w("  a table (`table:signals`), a route (`route:POST /api/chat/send`) or an event (`event:sync.done`).")
    w("- **Calls are best effort.** Only calls that resolve to a name defined in this repo are drawn. Dispatch through a")
    w("  table or callback is invisible, so *no callers listed* means *none resolved*, not *dead*. Imports, tables, routes")
    w("  and events are exact.")
    w("- The rules that must not be broken are in `CLAUDE.md`; section *Rules and what they govern* maps each one to files.")
    w("")

    # ---- package overview -----------------------------------------------------------------
    w("## Packages")
    w("")
    pkg_of = {m["id"]: m["package"] for m in modules}
    pkg_docs: dict[str, str] = {}
    pkg_members: dict[str, list[dict]] = defaultdict(list)
    for m in modules:
        pkg_members[m["package"]].append(m)
        if m["path"].endswith("__init__.py"):
            pkg_docs[m["package"]] = m["doc"]
    weights: Counter = Counter()
    for e in data["edges"]:
        if e["kind"] == "imports" and e["src"] in pkg_of and e["dst"] in pkg_of:
            a, b = pkg_of[e["src"]], pkg_of[e["dst"]]
            if a != b and a != "tests":
                weights[(a, b)] += 1
    w("```mermaid")
    w("flowchart LR")
    ids = {p: p.replace(".", "_") for p in sorted(pkg_members) if p != "tests"}
    for p, i in ids.items():
        w(f'  {i}["{p}"]')
    for (a, b), n in sorted(weights.items()):
        if a in ids and b in ids:
            w(f"  {ids[a]} -->|{n}| {ids[b]}")
    w("```")
    w("")
    w("Edge labels count module-level imports between packages. Arrows point from importer to imported.")
    w("")
    w("| package | modules | what it is |")
    w("|---|---|---|")
    for p in sorted(pkg_members):
        w(f"| `{p}` | {len(pkg_members[p])} | {_trim(pkg_docs.get(p, ''), 110) or '—'} |")
    w("")

    # ---- entry points ---------------------------------------------------------------------
    w("## Entry points")
    w("")
    w("### Scripts")
    w("")
    w("| script | what it does | uses |")
    w("|---|---|---|")
    for m in scripts:
        used = [_short(e["dst"]) for e in edges_from(m["id"], "imports") if e["dst"].startswith("src.")]
        w(f"| `{m['path']}` | {_trim(m['doc'], 110) or '—'} | {_names(used, 6)} |")
    w("")
    w("### HTTP routes")
    w("")
    w("Non-GET routes require the `X-Fitness-Token` header (`src/api/guard.py`). `screen` = called from `src/web/index.html`.")
    w("")
    w("| route | handler | screen |")
    w("|---|---|---|")
    called = {e["dst"] for e in data["edges"] if e["kind"] == "calls_api"}
    for n in data["nodes"]:
        if n["kind"] == "route":
            h = n["handler"].replace("src.", "", 1)
            w(f"| `{n['name']}`{' 🔒' if n['guarded'] else ''} | `{h}` | {'yes' if n['id'] in called else ''} |")
    w("")

    # ---- modules --------------------------------------------------------------------------
    w("## Modules")
    w("")
    w("`imports` and `used by` are module-level edges (scripts and tests listed apart). `(lazy)` = imported inside a function.")
    w("")
    tested_by: dict[str, set[str]] = defaultdict(set)
    for e in data["edges"]:
        if e["kind"] == "tests":
            tested_by[e["dst"]].add(e["src"].replace("tests.", "", 1))
    members: dict[str, list[dict]] = defaultdict(list)
    for n in data["nodes"]:
        if n["kind"] in ("function", "class", "method", "constant"):
            members[n["module"]].append(n)

    for pkg in sorted(p for p in pkg_members if p != "tests"):
        w(f"### Package {pkg}")
        w("")
        for m in sorted(pkg_members[pkg], key=lambda x: x["id"]):
            if m["path"].endswith("__init__.py") and not m["doc"] and not members.get(m["id"]):
                continue                                  # an empty package marker says nothing
            w(f"#### {m['path']}")
            w("")
            if m["doc"]:
                w(_trim(m["doc"]))
                w("")
            imp = []
            for e in edges_from(m["id"], "imports"):
                if e["dst"].startswith("src."):
                    imp.append(_short(e["dst"]) + (" (lazy)" if e.get("lazy") else ""))
            users_src = [_short(e["src"]) for e in edges_to(m["id"], "imports") if e["src"].startswith("src.")]
            users_scripts = [e["src"] for e in edges_to(m["id"], "imports") if e["src"].startswith("scripts.")]
            lines = [f"- imports: {_names(imp, 12)}",
                     f"- used by: {_names(users_src + users_scripts)}"]
            ms = members.get(m["id"], [])
            classes = [x for x in ms if x["kind"] == "class"]
            funcs = [x for x in ms if x["kind"] == "function" and x["public"]]
            consts = [x for x in ms if x["kind"] == "constant" and x["public"]]
            private = [x for x in ms if x["kind"] in ("function",) and not x["public"]]
            defs = []
            for cl in classes:
                meths = [x["name"].split(".", 1)[1] for x in ms if x["kind"] == "method" and x["name"].startswith(cl["name"] + ".")
                         and not x["name"].split(".")[-1].startswith("_")]
                defs.append(f"class {cl['name']}" + (f" [{', '.join(meths[:8])}{' …' if len(meths) > 8 else ''}]" if meths else ""))
            defs += [f.get("signature", f["name"]) for f in funcs]
            if defs:
                shown = defs[:DEF_CAP]
                lines.append("- defs: " + "; ".join(shown) + (f"; … +{len(defs) - DEF_CAP}" if len(defs) > DEF_CAP else ""))
            if consts:
                lines.append("- constants: " + _names([x["name"] for x in consts], 12))
            if private:
                lines.append(f"- private helpers: {len(private)}")
            reads = sorted({edge["dst"][6:] for n in ms + [m] for edge in edges_from(n["id"], "reads")})
            writes = sorted({edge["dst"][6:] for n in ms + [m] for edge in edges_from(n["id"], "writes")})
            if reads or writes:
                lines.append(f"- tables: reads {_names(reads, 12)}; writes {_names(writes, 12)}")
            events = sorted({edge["dst"][6:] for n in ms + [m] for edge in edges_from(n["id"], "emits")})
            if events:
                lines.append(f"- emits: {_names(events, 12)}")
            tb = tested_by.get(m["id"])
            if tb:
                lines.append(f"- tested by: {_names(tb, 8)}")
            out.extend(lines)
            w("")

    # ---- tables ---------------------------------------------------------------------------
    w("## Tables")
    w("")
    w("Columns as the migrations leave them (`*` = primary key). Writers and readers are the modules whose own SQL touches")
    w("the table; most writes go through `db.store` helpers, so look there first and use `show` for the callers.")
    w("")
    for n in data["nodes"]:
        if n["kind"] != "table":
            continue
        cols = ", ".join(col["name"] + ("*" if col["pk"] else "") for col in n["columns"])
        w(f"### {n['name']}")
        w("")
        w(f"- columns: {cols}")
        if n["foreign_keys"]:
            w("- references: " + ", ".join(f"{f['column']} → {f['table']}" for f in n["foreign_keys"]))
        wr = sorted({_short(owner_module(e["src"])) for e in edges_to(n["id"], "writes")})
        rd = sorted({_short(owner_module(e["src"])) for e in edges_to(n["id"], "reads")})
        w(f"- written by: {_names(wr, 12)}")
        w(f"- read by: {_names(rd, 12)}")
        w("")

    # ---- events ---------------------------------------------------------------------------
    w("## Log events")
    w("")
    w("Everything `src/applog.py` can write. Read them with `python scripts/logs.py`.")
    w("")
    w("| event | emitted by |")
    w("|---|---|")
    for n in data["nodes"]:
        if n["kind"] == "event":
            who = [x["src"].replace("src.", "", 1) for x in edges_to(n["id"], "emits")]
            w(f"| `{n['name']}` | {_names(who, 6)} |")
    w("")

    # ---- rules ----------------------------------------------------------------------------
    w("## Rules and what they govern")
    w("")
    w("Each section of `CLAUDE.md` and the files it names. Read the rule before changing the files beside it.")
    w("")
    for n in data["nodes"]:
        if n["kind"] == "rule":
            gov = [_short(e["dst"]) for e in edges_from(n["id"], "governs")]
            if gov:
                w(f"- **{n['name']}** — {_names(gov, 14)}")
    w("")

    # ---- structure ------------------------------------------------------------------------
    w("## Structure notes")
    w("")
    top = Counter()
    for e in data["edges"]:
        if e["kind"] == "imports" and e["dst"].startswith("src.") and not e["src"].startswith("tests."):
            top[e["dst"]] += 1
    w("Most depended on (importers among src and scripts):")
    w("")
    for mod, n in top.most_common(12):
        w(f"- `{_short(mod)}` — {n}")
    w("")
    graph_hard: dict[str, set[str]] = defaultdict(set)
    graph_all: dict[str, set[str]] = defaultdict(set)
    for e in data["edges"]:
        if e["kind"] == "imports" and e["src"].startswith("src.") and e["dst"].startswith("src."):
            graph_all[e["src"]].add(e["dst"])
            if not e.get("lazy"):
                graph_hard[e["src"]].add(e["dst"])
    hard = _sccs(graph_hard)
    soft = [c_ for c_ in _sccs(graph_all) if not any(set(c_) <= set(h) for h in hard)]
    w("Import cycles at module level" + (": none." if not hard else ":"))
    for comp in hard:
        w(f"- {', '.join(_short(x) for x in comp)}")
    w("")
    w("Cycles that exist only through function-level (lazy) imports" + (": none." if not soft else ":"))
    for comp in soft:
        w(f"- {', '.join(_short(x) for x in comp)}")
    w("")
    imported = {e["dst"] for e in data["edges"] if e["kind"] == "imports" and not e["src"].startswith("tests.")}
    orphans = [_short(m["id"]) for m in src if m["id"] not in imported and not m["path"].endswith("__init__.py")]
    w("src modules nothing in src or scripts imports (entry points, or candidates for removal): " + _names(orphans, 30))
    w("")
    return "\n".join(out).rstrip() + "\n"
